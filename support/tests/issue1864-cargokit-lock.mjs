// Cloud-only normalization of one proven checkout-root path difference.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const [checkoutArg, destination, variant] = process.argv.slice(2);
function requireCondition(condition, message) {
  if (!condition) throw new Error(message);
}
requireCondition(process.argv.slice(2).length === 3, 'Expected checkout, destination and variant');
const checkout = fs.realpathSync(checkoutArg);
requireCondition(checkout === checkoutArg, 'Checkout root must be canonical');
requireCondition(['baseline', 'candidate'].includes(variant), 'Unknown variant');
const expectedSource = path.join(checkout,
  'packages/localsend_isolates/rust_builder/cargokit/build_tool');
requireCondition(fs.realpathSync(expectedSource) === expectedSource,
  'Vendored build_tool source must not escape through a symlink');
const rawPath = path.join(destination, 'cargokit-runner-pubspec.lock');
const pubspecPath = path.join(destination, 'cargokit-runner-pubspec.yaml');
for (const file of [rawPath, pubspecPath]) {
  requireCondition(fs.lstatSync(file).isFile(), 'Retained runner input must be a regular nonsymlink file');
}
const rawBytes = fs.readFileSync(rawPath);
const raw = rawBytes.toString('utf8');
requireCondition(Buffer.from(raw, 'utf8').equals(rawBytes),
  'Generated lock must round-trip as UTF-8 without byte loss');
const pubspec = fs.readFileSync(pubspecPath, 'utf8');
requireCondition(!raw.includes('\r') && !pubspec.includes('\r'),
  'Unexpected generated line endings');
function decodeAbsolutePath(value) {
  let decoded;
  if (value.startsWith('"')) decoded = JSON.parse(value);
  else {
    requireCondition(/^\/[A-Za-z0-9_./-]+$/.test(value),
      'Unsupported unquoted path representation');
    decoded = value;
  }
  requireCondition(typeof decoded === 'string' && path.isAbsolute(decoded),
    'Expected absolute dependency path');
  requireCondition(decoded.startsWith(checkout + '/'),
    'Dependency path is outside exact checkout');
  requireCondition(fs.realpathSync(decoded) === expectedSource,
    'Dependency does not resolve to expected vendored build_tool');
  return decoded;
}
const pubspecMatches = [...pubspec.matchAll(
  /^dependencies:\n  build_tool:\n    path: (.+)$/gm)];
requireCondition(pubspecMatches.length === 1,
  'Expected one generated build_tool dependency context');
const generatedSourcePath = decodeAbsolutePath(pubspecMatches[0][1]);
const packageHeaders = [...raw.matchAll(/^  build_tool:$/gm)];
requireCondition(packageHeaders.length === 1, 'Expected one build_tool package');
requireCondition(raw.startsWith('# Generated by pub\n') && /^packages:$/m.test(raw),
  'Unexpected lock header');
const start = packageHeaders[0].index;
const remaining = raw.slice(start);
const nextHeader = remaining.slice('  build_tool:\n'.length)
  .search(/^  [A-Za-z0-9_]+:$|^[A-Za-z0-9_]+:$/m);
requireCondition(nextHeader >= 0, 'Missing following package or SDK block');
const end = start + '  build_tool:\n'.length + nextHeader;
const block = raw.slice(start, end);
const blockMatch = block.match(
  /^  build_tool:\n    dependency: "direct main"\n    description:\n      path: (.+)\n      relative: false\n    source: path\n    version: "1\.0\.0"\n$/);
requireCondition(blockMatch !== null, 'Unexpected build_tool lock context');
const lockedSourcePath = decodeAbsolutePath(blockMatch[1]);
requireCondition(raw.split(checkout).length - 1 === 1,
  'Checkout root must occur exactly once in entire raw lock');
const pathLine = '      path: ' + blockMatch[1] + '\n';
requireCondition(block.split(pathLine).length - 1 === 1,
  'Expected exactly one path line inside build_tool description');
const rootIndex = raw.indexOf(checkout);
const pathLineStart = start + block.indexOf(pathLine);
requireCondition(rootIndex >= pathLineStart &&
  rootIndex + checkout.length < pathLineStart + pathLine.length,
  'Only checkout-root occurrence must be inside validated dependency path');
const token = '__ISSUE1864_CHECKOUT_ROOT__';
requireCondition(!raw.includes(token), 'Normalization token already present');
const normalized = raw.slice(0, rootIndex) + token +
  raw.slice(rootIndex + checkout.length);
fs.writeFileSync(path.join(destination, 'cargokit-runner-normalized.lock'), normalized);
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
fs.writeFileSync(path.join(destination, 'cargokit-lock-normalization.json'),
  JSON.stringify({variant, checkout, expectedSource, generatedSourcePath,
    lockedSourcePath, rawSha256: sha256(rawBytes), normalizedSha256: sha256(normalized),
    replacementCount: 1, replacementContext: 'packages.build_tool.description.path',
    remainingBytesPreserved: true}, null, 2) + '\n');
